1. Prepare Your App for Release
Test Your App: Ensure your app is thoroughly tested and bug-free.
Versioning: Update your app version in the build.gradle file (versionCode and versionName).

Sign Your App:
Go to Build → Generate Signed Bundle/APK in Android Studio.
Select Android App Bundle (recommended) or APK.
Create or use an existing key store, and sign the app with the keystore file.
Optimize: Minify your app using ProGuard (optional but recommended).

2. Create a Developer Account
Visit the Google Play Console.
Sign in with your Google account.
Pay the one-time $25 registration fee.

3. Prepare Store Listing
Title: Choose a unique title for your app.
short Description: Provide a concise, informative app description.
full Description
Screenshots: Include screenshots (min 2) for each screen size (phone, tablet, etc.).
App Icon: A 512x512 PNG icon.
Feature Graphic: A 1024x500 feature graphic for showcasing the app on the store.
Categorization: Select the app category (e.g., Education, Game, etc.).
Content Rating: Fill out a content rating questionnaire.
Privacy Policy: Provide a URL to your privacy policy.

4. Upload Your App
In the Play Console, go to All Apps and click Create App.
Fill in the app details, including languages, app type, and distribution.
Upload your App Bundle (.aab) or APK file.

5. Set Pricing and Distribution
Choose if your app will be Free or Paid.
Select the countries where the app will be available.
Choose distribution options like device types (phones, tablets, etc.).

6. Review and Publish
Review your app details to ensure everything is correct.
Submit the app for review by Google.
It may take a few hours to a few days for Google to review and approve your app.

7. App Maintenance
Monitor user feedback, crashes, and ANRs in the Play Console.
Release updates as needed to improve app performance and user experience.
After approval, your app will be live on the Play Store!*/