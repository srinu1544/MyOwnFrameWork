package com.example.myownframework.Kotlin_Android.JetpackCompose

import androidx.compose.material3.Scaffold


/*In Jetpack Compose, Scaffold is a fundamental layout component that provides a structured
framework for designing layouts. It is similar to the concept of a material design scaffold,
 which provides a base layout structure for various UI elements, such as the top app bar,
 bottom navigation bar, floating action button (FAB), drawers, and more.

Key Purpose of Scaffold:
Scaffold helps in building a consistent layout by managing the placement of common UI components.
 It provides slots for commonly used UI elements like:

TopAppBar: A bar at the top, often used for titles and actions.
BottomAppBar or BottomNavigation: A bar at the bottom, typically used for navigation.
FloatingActionButton (FAB): A floating button used for primary actions.
Drawer: A side navigation panel that can be pulled from the side.
Snackbar: For temporary messages. */

